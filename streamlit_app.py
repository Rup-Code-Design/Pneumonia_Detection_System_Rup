# ============================================================
# GET MODEL INPUT SIZE
# ============================================================

def get_model_input_size(model):

    try:

        input_shape = model.input_shape

        if isinstance(
            input_shape,
            list
        ):

            input_shape = input_shape[0]

        height = input_shape[1]
        width = input_shape[2]

        if (
            height is not None
            and width is not None
        ):

            return (
                int(height),
                int(width)
            )

    except Exception:
        pass

    return (
        224,
        224
    )


# ============================================================
# CHECK GRAYSCALE
# ============================================================

def is_grayscale_image(image):

    # --------------------------------------------------------
    # Native grayscale formats
    # --------------------------------------------------------

    if image.mode in [
        "1",
        "L",
        "I",
        "F",
        "I;16"
    ]:

        return True

    # --------------------------------------------------------
    # Convert to RGB for pixel comparison
    # --------------------------------------------------------

    rgb_image = image.convert(
        "RGB"
    )

    image_array = np.asarray(
        rgb_image
    )

    if (
        image_array.ndim != 3
        or image_array.shape[-1] != 3
    ):

        return True

    red = image_array[:, :, 0]
    green = image_array[:, :, 1]
    blue = image_array[:, :, 2]

    return (
        np.array_equal(
            red,
            green
        )
        and
        np.array_equal(
            green,
            blue
        )
    )


# ============================================================
# PREPROCESS IMAGE
# ============================================================

def preprocess_image(
    image,
    target_size
):

    # --------------------------------------------------------
    # Convert to grayscale
    # --------------------------------------------------------

    grayscale = image.convert(
        "L"
    )

    # --------------------------------------------------------
    # Resize
    # --------------------------------------------------------

    grayscale = grayscale.resize(
        target_size,
        Image.Resampling.BILINEAR
    )

    # --------------------------------------------------------
    # NumPy
    # --------------------------------------------------------

    image_array = np.asarray(
        grayscale
    ).astype(
        np.float32
    )

    # --------------------------------------------------------
    # Normalize
    # --------------------------------------------------------

    image_array = (
        image_array / 255.0
    )

    # --------------------------------------------------------
    # Grayscale → RGB
    #
    # Your models use:
    # (224, 224, 3)
    #
    # --------------------------------------------------------

    image_array = np.stack(
        [
            image_array,
            image_array,
            image_array
        ],
        axis=-1
    )

    # --------------------------------------------------------
    # Batch dimension
    # --------------------------------------------------------

    image_array = np.expand_dims(
        image_array,
        axis=0
    )

    return image_array


# ============================================================
# MODALITY PREDICTION
# ============================================================

def predict_modality(
    model,
    image
):

    target_size = get_model_input_size(
        model
    )

    processed_image = preprocess_image(
        image,
        target_size
    )

    prediction = model.predict(
        processed_image,
        verbose=0
    )

    prediction = np.asarray(
        prediction
    ).reshape(-1)

    # --------------------------------------------------------
    # Require exactly 3 classes
    # --------------------------------------------------------

    if len(prediction) != 3:

        raise ValueError(
            f"""
Invalid modality model output.

Expected 3 classes:
X-ray
CT
MRI

Received:
{len(prediction)}
"""
        )

    # --------------------------------------------------------
    # Ensure probabilities
    # --------------------------------------------------------

    if (
        np.any(prediction < 0)
        or
        np.any(prediction > 1)
        or
        not np.isclose(
            np.sum(prediction),
            1.0,
            atol=1e-3
        )
    ):

        prediction = tf.nn.softmax(
            prediction
        ).numpy()

    # --------------------------------------------------------
    # Predicted class
    # --------------------------------------------------------

    class_index = int(
        np.argmax(prediction)
    )

    confidence = float(
        prediction[class_index]
    )

    modality = MODALITY_LABELS.get(
        class_index,
        "Unknown"
    )

    return (
        modality,
        confidence,
        prediction
    )


# ============================================================
# PNEUMONIA PREDICTION
# ============================================================

def predict_pneumonia(
    model,
    image
):

    target_size = get_model_input_size(
        model
    )

    processed_image = preprocess_image(
        image,
        target_size
    )

    prediction = model.predict(
        processed_image,
        verbose=0
    )

    prediction = np.asarray(
        prediction
    ).reshape(-1)

    # ========================================================
    # TWO CLASS SOFTMAX
    # ========================================================

    if len(prediction) == 2:

        if (
            np.any(prediction < 0)
            or
            np.any(prediction > 1)
            or
            not np.isclose(
                np.sum(prediction),
                1.0,
                atol=1e-3
            )
        ):

            prediction = tf.nn.softmax(
                prediction
            ).numpy()

        class_index = int(
            np.argmax(prediction)
        )

        confidence = float(
            prediction[class_index]
        )

        diagnosis = PNEUMONIA_LABELS[
            class_index
        ]

        return (
            diagnosis,
            confidence,
            prediction
        )

    # ========================================================
    # SINGLE SIGMOID
    # ========================================================

    if len(prediction) == 1:

        probability = float(
            prediction[0]
        )

        if (
            probability < 0
            or
            probability > 1
        ):

            probability = float(
                tf.sigmoid(
                    prediction[0]
                ).numpy()
            )

        if probability >= 0.5:

            diagnosis = "Pneumonia"

            confidence = probability

        else:

            diagnosis = "Normal"

            confidence = (
                1.0 - probability
            )

        return (
            diagnosis,
            confidence,
            probability
        )

    # ========================================================
    # INVALID MODEL
    # ========================================================

    raise ValueError(
        f"""
Invalid pneumonia model output.

Expected:
2-class softmax
OR
1-class sigmoid

Received:
{len(prediction)} outputs
"""
    )


