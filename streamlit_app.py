def create_pdf_report(
    image,
    modality,
    modality_confidence,
    diagnosis=None,
    diagnosis_confidence=None
):

    pdf_buffer = io.BytesIO()

    document = SimpleDocTemplate(
        pdf_buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        fontSize=18,
        leading=22,
        spaceAfter=8
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        alignment=TA_CENTER,
        fontSize=10,
        leading=14,
        spaceAfter=15
    )

    heading_style = ParagraphStyle(
        "ReportHeading",
        parent=styles["Heading2"],
        fontSize=13,
        leading=16,
        spaceBefore=10,
        spaceAfter=8
    )

    normal_style = ParagraphStyle(
        "ReportNormal",
        parent=styles["Normal"],
        fontSize=10,
        leading=14
    )

    result_style = ParagraphStyle(
        "ReportResult",
        parent=styles["Normal"],
        alignment=TA_CENTER,
        fontSize=16,
        leading=20,
        spaceAfter=10
    )

    story = []

    # ========================================================
    # TITLE
    # ========================================================

    story.append(
        Paragraph(
            "Pneumonia Detection System from X-ray Images",
            title_style
        )
    )

    story.append(
        Paragraph(
            "Medical Image Analysis Report",
            subtitle_style
        )
    )

    # ========================================================
    # DATE
    # ========================================================

    report_date = datetime.now().strftime(
        "%d %B %Y, %I:%M:%S %p"
    )

    # ========================================================
    # INFORMATION TABLE
    # ========================================================

    story.append(
        Paragraph(
            "Analysis Information",
            heading_style
        )
    )

    report_data = [
        [
            "Analysis Date",
            report_date
        ],
        [
            "Image Type",
            "Grayscale"
        ],
        [
            "Detected Modality",
            modality
        ],
        [
            "Modality Confidence",
            f"{modality_confidence * 100:.2f}%"
        ]
    ]

    # --------------------------------------------------------
    # Add pneumonia result only for X-ray
    # --------------------------------------------------------

    if diagnosis is not None:

        report_data.append(
            [
                "Final Result",
                diagnosis
            ]
        )

        report_data.append(
            [
                "Diagnosis Confidence",
                f"{diagnosis_confidence * 100:.2f}%"
            ]
        )

    report_table = Table(
        report_data,
        colWidths=[
            55 * mm,
            105 * mm
        ]
    )

    report_table.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (0, -1),
                    colors.lightgrey
                ),
                (
                    "GRID",
                    (0, 0),
                    (-1, -1),
                    0.5,
                    colors.grey
                ),
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "MIDDLE"
                ),
                (
                    "FONTSIZE",
                    (0, 0),
                    (-1, -1),
                    9
                ),
                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    6
                ),
                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    6
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    6
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    6
                )
            ]
        )
    )

    story.append(
        report_table
    )

    story.append(
        Spacer(1, 12)
    )

    # ========================================================
    # IMAGE
    # ========================================================

    story.append(
        Paragraph(
            "Analyzed Image",
            heading_style
        )
    )

    image_buffer = io.BytesIO()

    image.convert(
        "RGB"
    ).save(
        image_buffer,
        format="JPEG"
    )

    image_buffer.seek(0)

    report_image = ReportLabImage(
        image_buffer,
        width=100 * mm,
        height=100 * mm
    )

    story.append(
        report_image
    )

    story.append(
        Spacer(1, 12)
    )

    # ========================================================
    # FINAL RESULT
    # ========================================================

    if diagnosis is not None:

        story.append(
            Paragraph(
                "Final Pneumonia Analysis",
                heading_style
            )
        )

        story.append(
            Paragraph(
                f"<b>{diagnosis}</b>",
                result_style
            )
        )

        story.append(
            Paragraph(
                f"Model confidence: "
                f"{diagnosis_confidence * 100:.2f}%",
                ParagraphStyle(
                    "Confidence",
                    parent=normal_style,
                    alignment=TA_CENTER,
                    spaceAfter=15
                )
            )
        )

    else:

        story.append(
            Paragraph(
                f"The uploaded image was identified as "
                f"<b>{modality}</b>. Pneumonia detection was "
                f"not performed because the pneumonia model "
                f"is intended only for chest X-ray images.",
                normal_style
            )
        )

    # ========================================================
    # DISCLAIMER
    # ========================================================

    story.append(
        Spacer(1, 15)
    )

    story.append(
        Paragraph(
            "<b>Research Disclaimer:</b> This application is "
            "intended for research and decision-support purposes. "
            "The result should not be considered a medical diagnosis "
            "and should be reviewed by a qualified healthcare "
            "professional.",
            normal_style
        )
    )

    document.build(
        story
    )

    pdf_buffer.seek(0)

    return pdf_buffer.getvalue()


